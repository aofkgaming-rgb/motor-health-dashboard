/**
 * CSV and Excel (.xlsx) export. Both stream, so a 30-day export does not need much memory.
 * Columns are the SD-card columns (or the subset the user picked), then custom parameters.
 */
import type express from 'express';
import ExcelJS from 'exceljs';
import { CSV_COLUMNS, TelemetryRow, csvHeader, rowToCells, rowToCsvLine } from '../src/shared/contract';

export interface ExportMeta {
  title: string;
  source: string;
  device: string;
  from: number;
  to: number;
  resolution: string;
  generatedBy: string;
  tzOffsetMin: number;
  schema: number;
}

export async function sendExport(
  res: express.Response,
  rows: Iterable<TelemetryRow>,
  opts: { format: 'csv' | 'xlsx'; filename: string; columns: string[]; extraKeys: string[]; meta: ExportMeta },
): Promise<number> {
  const { format, filename, columns, extraKeys, meta } = opts;
  let count = 0;

  if (format === 'csv') {
    res.setHeader('Content-Type', 'text/csv; charset=utf-8');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}.csv"`);
    res.write(csvHeader(extraKeys, columns) + '\r\n');
    for (const r of rows) {
      res.write(rowToCsvLine(r, extraKeys, columns) + '\r\n');
      count++;
    }
    res.end();
    return count;
  }

  res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
  res.setHeader('Content-Disposition', `attachment; filename="${filename}.xlsx"`);
  const wb = new ExcelJS.stream.xlsx.WorkbookWriter({ stream: res, useStyles: true });
  wb.creator = 'MHM dashboard';
  const ws = wb.addWorksheet('Data', { views: [{ state: 'frozen', ySplit: 1 }] });
  const tzLabel = `local_time_utc${meta.tzOffsetMin >= 0 ? '+' : '-'}${String(Math.floor(Math.abs(meta.tzOffsetMin) / 60)).padStart(2, '0')}:${String(Math.abs(meta.tzOffsetMin) % 60).padStart(2, '0')}`;
  const header = [...columns, ...extraKeys];
  const hasTs = columns.includes('timestamp_utc');
  ws.columns = [
    ...(hasTs ? [{ header: tzLabel, key: '_local', width: 20, style: { numFmt: 'yyyy-mm-dd hh:mm:ss' } }] : []),
    ...header.map((h) => ({
      header: h,
      key: h,
      width: h === 'timestamp_utc' ? 20 : Math.max(9, h.length + 2),
      style: h === 'timestamp_utc' ? { numFmt: 'yyyy-mm-dd hh:mm:ss' } : {},
    })),
  ];
  ws.getRow(1).font = { bold: true };
  ws.getRow(1).commit();
  for (const r of rows) {
    const all = rowToCells(r);
    const cells: unknown[] = [];
    if (hasTs) cells.push(new Date(r.ts + meta.tzOffsetMin * 60000));
    for (const c of columns) {
      if (c === 'timestamp_utc') cells.push(new Date(r.ts));
      else cells.push(all[CSV_COLUMNS.indexOf(c as any)] ?? null);
    }
    for (const k of extraKeys) cells.push(r.extra?.[k] ?? null);
    ws.addRow(cells).commit();
    count++;
  }
  ws.commit();

  const about = wb.addWorksheet('About');
  about.columns = [
    { header: 'Item', key: 'k', width: 22 },
    { header: 'Value', key: 'v', width: 70 },
  ];
  about.getRow(1).font = { bold: true };
  const fmt = (t: number) => new Date(t + meta.tzOffsetMin * 60000).toISOString().replace('T', ' ').slice(0, 19);
  [
    ['Export', meta.title],
    ['Data source', meta.source === 'demo' ? 'DEMO — simulated by the server, not measured' : 'Device (measured)'],
    ['Device', meta.device],
    ['From (local)', fmt(meta.from)],
    ['To (local)', fmt(meta.to)],
    ['Resolution', meta.resolution],
    ['Rows', String(count)],
    ['Generated by', meta.generatedBy],
    ['Generated at (local)', fmt(Date.now())],
    ['Schema version', String(meta.schema)],
    ['Notes', 'Empty cells are missing values, never 0. Same columns as the SD-card log on Board B, plus a local-time column.'],
  ].forEach(([k, v]) => about.addRow({ k, v }).commit());
  about.commit();
  await wb.commit();
  return count;
}
